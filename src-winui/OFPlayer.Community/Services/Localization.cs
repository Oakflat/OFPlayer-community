namespace OFPlayer_WinUI.Services;
/// <summary>
/// Localization strings are read explicitly by each surface and refreshed on
/// <see cref = "Localization.LanguageChanged"/>. English and Simplified Chinese
/// retain the typed source table; Japanese, French and German use embedded JSON
/// catalogs with exact key and named-parameter validation.
/// </summary>
public static partial class Localization
{
    /// <summary>`system` | `en` | `zh-CN` | `ja` | `fr` | `de` — the same domain as the old LanguageOption.</summary>
    public static event Action? LanguageChanged;
    private static string preference = "system";
    /// <summary>Raised when the active language changes so views can re-read strings.</summary>
    public static string Preference => preference;
    /// <summary>
    /// The language actually in effect. `system` resolves from the OS UI language,
    /// matching the old client's getResolvedLocalePreference behavior.
    /// </summary>
    public static string Resolved => Resolve(preference, System.Globalization.CultureInfo.CurrentUICulture);
    public static System.Globalization.CultureInfo Culture => preference == "system" ? System.Globalization.CultureInfo.CurrentCulture : System.Globalization.CultureInfo.GetCultureInfo(Resolved switch
    {
        "ja" => "ja-JP",
        "fr" => "fr-FR",
        "de" => "de-DE",
        "zh-CN" => "zh-CN",
        _ => "en-US",
    });

    public static string Resolve(string value, System.Globalization.CultureInfo systemCulture) => value switch
    {
        "en" or "zh-CN" or "ja" or "fr" or "de" => value,
        _ => systemCulture.TwoLetterISOLanguageName.ToLowerInvariant() switch
        {
            "zh" => "zh-CN",
            "ja" => "ja",
            "fr" => "fr",
            "de" => "de",
            _ => "en",
        },
    };
    public static bool IsChinese => Resolved == "zh-CN";

    /// <summary>Applies a language preference. Unknown values keep the current language.</summary>
    public static void ApplyPreference(string? value)
    {
        var next = value is "system" or "en" or "zh-CN" or "ja" or "fr" or "de" ? value : preference;
        if (next == preference)
        {
            return;
        }

        preference = next;
        LanguageChanged?.Invoke();
    }

    /// <summary>
    /// Looks up <paramref name = "key"/>. An unknown key returns the key itself — visible
    /// in the UI rather than silently blank, which makes a missed string obvious.
    /// </summary>
    public static string Get(string key)
    {
        if (!Strings.TryGetValue(key, out var entry))
        {
            return key;
        }

        return Resolved switch
        {
            "zh-CN" => entry.Zh,
            "ja" or "fr" or "de" => AdditionalLocales.Value[Resolved][key],
            _ => entry.En,
        };
    }

    public static string Format(string key, params (string Name, string Value)[] arguments)
    {
        var text = Get(key);
        foreach (var(name, value)in arguments)
        {
            text = text.Replace("{" + name + "}", value, StringComparison.Ordinal);
        }

        return text;
    }

